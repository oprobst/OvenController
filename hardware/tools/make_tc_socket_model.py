"""Generates a simplified 3D model (VRML) of the RS PRO 381-7564 thermocouple PCB socket (J8, J10).

RS offers CAD data only through a sign-in service, so the model is built from the datasheet
dimensions used for the footprint `oven:RS_381-7564_Horizontal` (RS datasheet A700000008891647,
"Miniature PCB Socket"): body 16.6 x 20.5 x 8 mm in IEC green (type K), plug face 4.25 mm in front
of the pins, 2 pins dia 1.3 mm at 7.9 mm pitch reaching 4 mm below the board, through hole
dia 2.7 mm 10.25 mm behind the pins. Coordinates follow the footprint (origin between the pins,
plug side towards footprint +Y); VRML units for KiCad are 0.1 inch.

Run with any Python 3:
    python hardware/tools/make_tc_socket_model.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "lib" / "3dmodels" / "RS_381-7564.wrl"

WIDTH, DEPTH, HEIGHT = 16.6, 20.5, 8.0
FRONT_Y = 4.25                 # plug face, footprint coordinates (+Y = towards the plug)
PIN_X, PIN_W, PIN_DOWN = 3.95, 1.3, 4.0
HOLE_Y, HOLE_D = -10.25, 2.7
SLOT_W, SLOT_H, SLOT_Z = 1.2, 3.2, 4.0   # plug openings (flat pins of the miniature plug)

GREEN = (0.10, 0.55, 0.20)
DARK = (0.05, 0.05, 0.05)
METAL = (0.80, 0.78, 0.72)


def box(x0, x1, y0, y1, z0, z1):
    """Axis-aligned box in footprint mm (y down on the board) -> 3D (y up)."""
    ys = (-y1, -y0)
    pts = [(x, y, z) for z in (z0, z1) for y in ys for x in (x0, x1)]
    faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
    return pts, faces


def shape(parts, color):
    pts, idx = [], []
    for p, f in parts:
        base = len(pts)
        pts += p
        idx += [" ".join(str(base + i) for i in face) + " -1" for face in f]
    coords = ", ".join(f"{x / 2.54:.5f} {y / 2.54:.5f} {z / 2.54:.5f}" for x, y, z in pts)
    r, g, b = color
    return (f"Shape {{\n  appearance Appearance {{ material Material {{ diffuseColor {r} {g} {b} "
            f"specularColor 0.2 0.2 0.2 shininess 0.3 }} }}\n"
            f"  geometry IndexedFaceSet {{\n    coord Coordinate {{ point [ {coords} ] }}\n"
            f"    coordIndex [ {' '.join(idx)} ]\n  }}\n}}\n")


def main():
    back_y = FRONT_Y - DEPTH
    body = [box(-WIDTH / 2, WIDTH / 2, back_y, FRONT_Y, 0.0, HEIGHT)]
    eps = 0.05
    slots = [box(x - SLOT_W / 2, x + SLOT_W / 2, FRONT_Y - 0.5, FRONT_Y + eps,
                 SLOT_Z - SLOT_H / 2, SLOT_Z + SLOT_H / 2) for x in (-PIN_X, PIN_X)]
    hole = [box(-HOLE_D / 2, HOLE_D / 2, HOLE_Y - HOLE_D / 2, HOLE_Y + HOLE_D / 2, HEIGHT - 0.5, HEIGHT + eps)]
    pins = [box(x - PIN_W / 2, x + PIN_W / 2, -PIN_W / 2, PIN_W / 2, -PIN_DOWN, 0.5) for x in (-PIN_X, PIN_X)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("#VRML V2.0 utf8\n# RS PRO 381-7564, simplified, generated by hardware/tools/make_tc_socket_model.py\n"
                   + shape(body, GREEN) + shape(slots + hole, DARK) + shape(pins, METAL),
                   encoding="utf-8", newline="\n")
    print("written:", OUT)


if __name__ == "__main__":
    main()
